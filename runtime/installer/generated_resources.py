"""Frozen H10 loader-cache recipe for fresh archive-derived installer images."""
import hashlib
import os
from pathlib import Path
import re
import stat

from .disk_plan import InstallError

CONFIG='# Begin /etc/ld.so.conf\n/usr/local/lib\n/opt/lib\ninclude /etc/ld.so.conf.d/*.conf\n'
SEARCH=('usr/lib','lib64','usr/local/lib','opt/lib')


def digest(path):
    with Path(path).open('rb') as stream:return hashlib.file_digest(stream,'sha256').hexdigest()


def loader_namespace(root,entries):
    """Closed frozen LFS search inputs; reject extra tunables/search overrides."""
    root=Path(root)
    if root.resolve()!=root or not root.is_dir():raise InstallError('installer_loader_root')
    selected={'/etc/ld.so.conf','/usr/sbin/ldconfig','/lib','/lib64'}
    if (root/'etc/ld.so.conf').read_text()!=CONFIG or (root/'etc/tunables.conf').exists() or (root/'etc/tunables.conf').is_symlink():raise InstallError('installer_loader_search_policy')
    config=root/'etc/ld.so.conf.d'
    if config.resolve()!=config or not config.is_dir() or any(config.iterdir()):raise InstallError('installer_loader_search_policy')
    if not (root/'lib').is_symlink() or os.readlink(root/'lib')!='usr/lib' or (root/'lib64').is_symlink() or not (root/'lib64').is_dir() or (root/'usr/lib64').exists() or (root/'usr/lib64').is_symlink():raise InstallError('installer_loader_alias')
    for relative in SEARCH:
        directory=root/relative
        if not directory.exists() and not directory.is_symlink():
            if relative=='usr/lib':raise InstallError('installer_loader_input_missing')
            continue
        if directory.resolve()!=directory or not directory.is_dir():raise InstallError('installer_loader_search_policy')
        selected.add('/'+relative)
        for base,directories,files in os.walk(directory,followlinks=False):
            selected.update('/'+(Path(base)/name).relative_to(root).as_posix() for name in directories+files)
    device=root.stat().st_dev
    for virtual in selected:
        row=entries.get(virtual);path=root/virtual.lstrip('/')
        if not row or path.parent.resolve()!=path.parent:raise InstallError('installer_loader_unowned_input')
        info=path.lstat()
        if info.st_dev!=device or os.listxattr(path,follow_symlinks=False) or (info.st_mode,info.st_uid,info.st_gid)!=(row.get('mode'),row.get('uid'),row.get('gid')):raise InstallError('installer_loader_input_changed')
        if row.get('directory') is True:
            if not stat.S_ISDIR(info.st_mode):raise InstallError('installer_loader_input_changed')
        elif 'sha256' in row:
            if not stat.S_ISREG(info.st_mode) or digest(path)!=row['sha256']:raise InstallError('installer_loader_input_changed')
        elif not stat.S_ISLNK(info.st_mode) or os.readlink(path)!=row.get('symlink'):raise InstallError('installer_loader_input_changed')
    return selected


def generate_loader_cache(root,entries,system):
    """Actual native generator/readback; no source cache or aux state is copied."""
    root=Path(root);system.require_root()
    before=loader_namespace(root,entries)
    cache=root/'etc/ld.so.cache';auxiliary=root/'var/cache/ldconfig'
    if list((root/'etc').glob('ld.so.cache*')):raise InstallError('installer_loader_existing_output')
    for parent in (cache.parent,auxiliary.parent):
        info=parent.lstat()
        if parent.resolve()!=parent or not stat.S_ISDIR(info.st_mode) or info.st_uid!=0 or info.st_gid!=0 or info.st_mode&0o022 or info.st_dev!=root.stat().st_dev:raise InstallError('installer_loader_output_parent')
    if auxiliary.exists() or auxiliary.is_symlink():
        info=auxiliary.lstat()
        if auxiliary.resolve()!=auxiliary or (info.st_mode,info.st_uid,info.st_gid)!=(stat.S_IFDIR|0o700,0,0) or any(auxiliary.iterdir()):raise InstallError('installer_loader_auxiliary_state')
    system.run(['/usr/bin/chroot',str(root),'/usr/sbin/ldconfig','-X','-i'],timeout=120)
    if loader_namespace(root,entries)!=before:raise InstallError('installer_loader_namespace_changed')
    if sorted(path.name for path in cache.parent.glob('ld.so.cache*'))!=['ld.so.cache']:raise InstallError('installer_loader_unexpected_output')
    info=cache.lstat()
    if (info.st_mode,info.st_uid,info.st_gid,info.st_nlink)!=(stat.S_IFREG|0o644,0,0,1) or cache.stat().st_dev!=root.stat().st_dev or os.listxattr(cache,follow_symlinks=False):raise InstallError('installer_loader_output_metadata')
    output=system.run(['/usr/bin/chroot',str(root),'/usr/sbin/ldconfig','-p'],timeout=30)
    lines=output.splitlines()
    count=re.fullmatch(r"(\d+) libs found in cache `/etc/ld.so.cache'",lines[0]) if lines else None
    if not count or len(lines)<3 or lines[-1]!='Cache generated by: ldconfig (GNU libc) stable release version 2.44':raise InstallError('installer_loader_native_format')
    from .installed_boot import machinery
    runtime,_=machinery()
    cached=[]
    for line in lines[1:-1]:
        match=re.fullmatch(r'\s+(\S+) \(([^)]+)\) => (/\S+)',line)
        if not match:raise InstallError('installer_loader_native_format')
        source,canonical=runtime.target_resolve(root,match[3])
        if canonical not in before or digest(source)!=entries[canonical].get('sha256'):raise InstallError('installer_loader_cached_unowned_library')
        cached.append({'soname':match[1],'attributes':match[2],'path':match[3],'owned_path':canonical})
    if not cached or int(count[1])!=len(cached):raise InstallError('installer_loader_native_count')
    auxiliary_info=auxiliary.lstat()
    if auxiliary.resolve()!=auxiliary or (auxiliary_info.st_mode,auxiliary_info.st_uid,auxiliary_info.st_gid)!=(stat.S_IFDIR|0o700,0,0) or sorted(path.name for path in auxiliary.iterdir())!=['aux-cache']:raise InstallError('installer_loader_auxiliary_state')
    aux=auxiliary/'aux-cache';info=aux.lstat()
    if (info.st_mode,info.st_uid,info.st_gid,info.st_nlink)!=(stat.S_IFREG|0o600,0,0,1) or info.st_dev!=root.stat().st_dev or os.listxattr(aux,follow_symlinks=False):raise InstallError('installer_loader_auxiliary_state')
    auxiliary_digest=digest(aux);aux.unlink()
    for path in (cache,cache.parent,auxiliary):
        descriptor=os.open(path,os.O_RDONLY|os.O_CLOEXEC)
        try:os.fsync(descriptor)
        finally:os.close(descriptor)
    return {'generator':'/usr/sbin/ldconfig','generator_sha256':entries['/usr/sbin/ldconfig']['sha256'],
        'flags':['-X','-i'],'verified_inputs':len(before),'entries':cached,
        'output':'/etc/ld.so.cache','sha256':digest(cache),'bytes':cache.stat().st_size,
        'omitted_fresh_auxiliary_cache_sha256':auxiliary_digest,'package_inputs_unchanged':True,
        'source_cache_copied':False,'native_commands':2}
