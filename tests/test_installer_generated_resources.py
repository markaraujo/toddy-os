        self.patch=patch.object(Path,'lstat',root_fixture);self.patch.start();self.addCleanup(self.patch.stop)
        parent=self
        class NativeFixture:
            def require_root(self):pass
            def run(self,argv,**options):
                parent.calls.append(argv)
                if argv[-1]=='-i':
                    (parent.root/'etc/ld.so.cache').write_bytes(b'synthetic cache');(parent.root/'etc/ld.so.cache').chmod(0o644)
